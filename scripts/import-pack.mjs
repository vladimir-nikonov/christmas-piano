// Imports the theme art pack (an unpacked snow-notes-development.zip) into src/ui/pack-art.js.
//   node scripts/import-pack.mjs <unpacked-pack-dir>
// Takes the avatars (<theme>/avatars/av-<character>-<theme>.svg), the open level blocks
// (<theme>/blocks/block-<material>-open.svg) and the icon paths (<theme>/icons/<name>.svg).
// The SVGs are stored as strings so the UI can keep building its markup synchronously.

import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = process.argv[2];
if (!dir){ console.error('usage: node scripts/import-pack.mjs <unpacked-pack-dir>'); process.exit(1); }

const THEMES = ['pixel', 'plastic', 'winter', 'anime'];
// Same order as AVATARS in src/ui/art.js (avatar index is stored in the kids' profiles)
const CHARACTERS = ['kid', 'bow', 'kid2', 'bow2', 'cat', 'robot', 'panda', 'frog', 'alien', 'snow'];
const MATERIALS = ['wood', 'stone', 'iron', 'gold', 'diamond'];
const ICONS = ['arrow-down', 'camera', 'check', 'cross', 'film', 'fullscreen', 'fullscreen-exit', 'gear', 'home', 'keys', 'lock',
  'mic', 'music', 'pause', 'pencil', 'play', 'plus', 'rec', 'retry', 'share', 'speaker', 'star', 'stop', 'trash'];

const read = p => readFileSync(join(dir, p), 'utf8').trim();
// Accept only plain static SVG: an allowlist of shape elements and presentation attributes.
// Anything else (scripts, styles, animation, links, entities, comments, ids) stops the import.
const TAGS = new Set(['svg', 'g', 'path', 'rect', 'circle', 'ellipse', 'line', 'polygon', 'polyline', 'defs', 'linearGradient', 'radialGradient', 'stop']);
const ATTRS = new Set(['xmlns', 'viewBox', 'd', 'x', 'y', 'x1', 'y1', 'x2', 'y2', 'width', 'height', 'rx', 'ry', 'cx', 'cy', 'r', 'points',
  'fill', 'fill-opacity', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin', 'stroke-opacity', 'stroke-dasharray', 'opacity',
  'transform', 'shape-rendering', 'display', 'offset', 'stop-color', 'stop-opacity', 'gradientUnits', 'fx', 'fy']);
function clean(svg, file){
  const bad = why => { throw new Error(why + ' in ' + file); };
  if (!/^<svg[\s>]/.test(svg) || !/<\/svg>$/.test(svg)) bad('not a single <svg> element');
  if (/<!|<\?|&/.test(svg)) bad('comments, doctype, processing instructions or entities');
  const rest = svg.replace(/<\/?([A-Za-z][\w-]*)((?:\s+[\w:-]+="[^"<>]*")*)\s*\/?>/g, (m, tag, attrs) => {
    if (!TAGS.has(tag)) bad('element <' + tag + '>');
    for (const [, name, value] of attrs.matchAll(/\s+([\w:-]+)="([^"]*)"/g)){
      if (!ATTRS.has(name)) bad('attribute ' + name);
      if (/url\(|javascript:|expression/i.test(value)) bad('value of ' + name);
    }
    return '';
  });
  if (rest.trim()) bad('text or malformed markup');
  return svg.replace(/\s*xmlns="http:\/\/www\.w3\.org\/2000\/svg"/, '').replace(/>\s+</g, '><');
}

const avatars = {}, blocks = {};
for (const t of THEMES){
  avatars[t] = CHARACTERS.map(c => clean(read(t + '/avatars/av-' + c + '-' + t + '.svg'), c + '/' + t));
  blocks[t] = MATERIALS.map(m => clean(read(t + '/blocks/block-' + m + '-open.svg'), m + '/' + t));
}
// Icon paths are the same in every theme; the stroke style differs and comes from the theme CSS.
const icons = {};
for (const n of ICONS){
  const svg = clean(read('anime/icons/' + n + '.svg'), n), d = svg.match(/<path d="([^"]+)"/g);
  if (!d || d.length !== 1) throw new Error('icon must be one path: ' + n);
  icons[n] = d[0].slice(9, -1);
}

const out = '// Generated by scripts/import-pack.mjs from the theme art pack. Do not edit by hand.\n\n' +
  '// Avatars per theme, in AVATARS order (80x80 viewBox, no ids)\n' +
  'export const PACK_AVATARS = ' + JSON.stringify(avatars, null, 1) + ';\n\n' +
  '// Level blocks per theme, in LEVELS order (80x80 viewBox, no ids)\n' +
  'export const PACK_BLOCKS = ' + JSON.stringify(blocks, null, 1) + ';\n\n' +
  '// Icon paths (24x24, one stroked path each)\n' +
  'export const PACK_ICONS = ' + JSON.stringify(icons, null, 1) + ';\n';
const target = resolve(fileURLToPath(new URL('../src/ui/pack-art.js', import.meta.url)));
writeFileSync(target, out);
console.log('wrote', target, Math.round(out.length / 1024) + ' KB');
